use std::collections::HashMap;

// unpack_key reverses collector-ebpf's pack_key(tgid, syscall_nr as u32).
pub fn unpack_key(key: u64) -> (u32, i64) {
    let tgid = (key >> 32) as u32;
    let syscall_nr = (key & 0xFFFF_FFFF) as u32 as i64;
    (tgid, syscall_nr)
}

